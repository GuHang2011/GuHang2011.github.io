async page => {
  const base='http://127.0.0.1:8777', checks=[], errors=[], scans=[], requests=[];
  const ok=(value,label)=>{if(!value)throw Error(label);checks.push(label)};
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(/\.mp4(?:\?|$)/.test(request.url()))requests.push(request.url())});
  await page.unrouteAll({behavior:'ignoreErrors'});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'/');
  await page.evaluate(()=>{sessionStorage.removeItem('hang-gu-cinema-dismissed');localStorage.setItem('hang-gu-reader-theme','light');localStorage.setItem('hang-gu-language','zh')});
  requests.length=0;
  await page.reload();
  const root=page.locator('[data-project-cinema]'), panel=page.locator('#cinema-panel'), media=page.locator('.cinema-screen video');
  const play=async()=>{
    await media.evaluate(v=>{v.muted=true});
    if(await page.locator('[data-cinema-play]').isVisible())await page.locator('[data-cinema-play]').click();
    else await media.evaluate(v=>v.play());
    await page.waitForFunction(()=>{const v=document.querySelector('.cinema-screen video');return v&&!v.paused&&v.currentTime>0.15});
  };
  const tracks=()=>media.evaluate(v=>[...v.textTracks].filter(t=>t.mode==='showing').map(t=>t.language));
  const isPaused=()=>media.evaluate(v=>v.paused);
  ok(await root.isVisible()&&!await panel.isVisible(),'Default is a small, collapsed launcher');
  ok(await media.count()===0&&requests.length===0,'No floating media element or MP4 download before opening');
  await page.locator('[data-cinema-toggle]').focus();await page.keyboard.press('Enter');
  ok(await panel.isVisible()&&await page.locator('[data-cinema-minimize]').evaluate(e=>e===document.activeElement),'Keyboard opening focuses a visible window control');
  ok(await isPaused()&&requests.length===0,'Opening does not start playback or fetch the MP4');
  await page.waitForFunction(()=>[...document.querySelector('.cinema-screen video').textTracks].filter(t=>t.mode==='showing').map(t=>t.language).join()==='zh');
  ok((await tracks()).join()==='zh','Only Chinese captions selected before playback');
  await play();
  ok((await tracks()).join()==='zh','Only Chinese captions remain selected after metadata loads');
  await media.evaluate(v=>{v.currentTime=2});
  await page.locator('[data-cinema-minimize]').click();
  ok(await isPaused()&&!await panel.isVisible(),'Minimize pauses the video');
  const position=await media.evaluate(v=>v.currentTime);
  await page.locator('[data-cinema-toggle]').click();
  ok(await isPaused()&&Math.abs(await media.evaluate(v=>v.currentTime)-position)<0.05,'Reopening retains position and waits for user playback');
  await page.keyboard.press('Escape');
  ok(!await panel.isVisible()&&await page.locator('[data-cinema-toggle]').evaluate(e=>e===document.activeElement),'Escape collapses and restores keyboard focus');
  await page.locator('[data-cinema-toggle]').click();
  await page.locator('[data-language="en"]').click();
  ok((await tracks()).join()==='en'&&await page.locator('[data-cinema-title]').innerText()==='Virtual presenter','English changes title and chooses one caption track');
  await page.locator('[data-language="zh"]').click();
  const titles=['虚拟主播','主播操作流程','模型早停动画','数据处理动画'];
  const destinations=['demos/virtual-host/','demos/virtual-host/README.md','cases/kapt/#early-stopping','demos/data-preparation/'];
  for(let i=0;i<4;i++){
    await page.locator('[data-cinema-select]').selectOption(String(i));
    ok(await isPaused()&&await page.locator('[data-cinema-title]').innerText()===titles[i]&&await page.locator('[data-cinema-demo]').getAttribute('href')===destinations[i],`Film ${i+1}: correct title, destination, and no autoplay`);
    await play();
    ok(await media.evaluate(v=>v.duration>0&&v.videoWidth>0)&&(await tracks()).join()==='zh',`Film ${i+1}: decoded video and one caption track`);
  }
  await media.evaluate(v=>{window.cinemaOldVideo=v});
  await page.locator('[data-cinema-next]').click();
  ok(await page.locator('[data-cinema-select]').inputValue()==='0'&&await isPaused()&&await page.evaluate(()=>window.cinemaOldVideo.paused),'Next wraps to first film and stops old playback');
  await page.locator('[data-cinema-prev]').click();
  ok(await page.locator('[data-cinema-select]').inputValue()==='3','Previous wraps to last film');
  await page.locator('[data-cinema-gallery]').click();
  await page.waitForURL('**/#film-data');
  ok(!await panel.isVisible()&&await page.locator('#film-data').isVisible(),'Watch-in-page closes window and reveals matching gallery panel');
  ok(await page.locator('#project-films').evaluate(e=>!['fixed','absolute'].includes(getComputedStyle(e).position)&&e.getBoundingClientRect().width>700),'Original gallery stays full width in document flow');
  const gallery=page.locator('#film-data video');
  await gallery.evaluate(v=>{v.muted=true;return v.play()});
  await page.locator('[data-cinema-toggle]').click();await play();
  ok(await gallery.evaluate(v=>v.paused),'Floating playback pauses the gallery');
  await gallery.evaluate(v=>v.play());
  ok(await isPaused(),'Gallery playback pauses the floating video');
  await gallery.evaluate(v=>v.pause());
  await play();await page.evaluate(()=>dispatchEvent(new Event('beforeprint')));
  ok(await isPaused(),'Printing pauses floating playback');
  await page.evaluate(()=>dispatchEvent(new Event('afterprint')));
  await play();await page.evaluate(()=>dispatchEvent(new Event('pagehide')));
  ok(await isPaused(),'Page departure pauses playback');
  await play();
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'))});
  ok(await isPaused(),'Hidden tab event pauses playback');
  await page.evaluate(()=>delete document.hidden);
  await panel.locator('[data-cinema-dismiss]').click();
  ok(!await root.isVisible(),'Dismiss hides both player and launcher');
  await page.reload();ok(!await root.isVisible(),'Dismiss persists for this session');
  await page.locator('[data-cinema-open]').click();
  ok(await panel.isVisible()&&!await page.evaluate(()=>sessionStorage.getItem('hang-gu-cinema-dismissed')),'Introduction link restores dismissed player');
  await page.locator('[data-cinema-select]').selectOption('2');
  await page.route('**/kapt-early-stopping.mp4',route=>route.abort());
  await media.evaluate(v=>{v.muted=true});await page.locator('[data-cinema-play]').click();
  await page.locator('[data-cinema-retry]').waitFor({state:'visible'});
  ok((await page.locator('[data-cinema-status]').innerText()).includes('暂未加载')&&(await page.locator('[data-cinema-file]').getAttribute('href')).endsWith('kapt-early-stopping.mp4'),'Failed video gives retry and original-file link');
  await page.unroute('**/kapt-early-stopping.mp4');
  await page.locator('[data-cinema-retry]').click();await play();
  ok(!await page.locator('[data-cinema-error-actions]').isVisible()&&!await isPaused(),'Retry recovers real video playback');
  await page.locator('[data-cinema-next]').click();
  await page.locator('[data-cinema-prev]').click();
  ok(await page.locator('[data-cinema-title]').innerText()==='模型早停动画'&&await isPaused()&&!await page.locator('[data-cinema-error-actions]').isVisible(),'Fast switching leaves the chosen film ready and paused');
  await page.goto(base+'/');await page.locator('[data-cinema-toggle]').click();
  await page.addScriptTag({path:'output/frontend-audit/node_modules/axe-core/axe.min.js'});
  for(const theme of ['light','dark']){
    await page.locator('[data-reader-toggle]').click();
    await page.locator(`button[data-reader-theme="${theme}"]`).click();
    await page.locator('[data-reader-toggle]').click();
    const scan=await page.evaluate(async()=>{const r=await axe.run({include:['[data-project-cinema]','[data-cinema-open]']},{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}});return r.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))});
    scans.push({theme,violations:scan});ok(scan.length===0,`${theme}: player accessibility scan`);
  }
  await page.locator('[data-reader-toggle]').click();await page.locator('button[data-reader-theme="light"]').click();await page.locator('[data-reader-toggle]').click();
  for(const [width,height] of [[320,568],[390,844],[768,1024],[1440,1000],[844,390]]){
    await page.setViewportSize({width,height});
    const bounds=await panel.boundingBox();
    ok(bounds.x>=0&&bounds.y>=0&&bounds.x+bounds.width<=width+1&&bounds.y+bounds.height<=height+1,`${width}×${height}: panel contained in viewport`);
    ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${width}×${height}: no horizontal overflow`);
    await page.locator('[data-cinema-gallery]').scrollIntoViewIfNeeded();
    ok(await page.locator('[data-cinema-gallery]').isVisible(),`${width}×${height}: bottom controls reachable`);
  }
  await page.setViewportSize({width:390,height:844});
  await panel.evaluate(e=>e.scrollTop=0);
  ok(await panel.evaluate(e=>getComputedStyle(e).animationName)==='none','Reduced-motion preference disables window entrance animation');
  await page.screenshot({path:'output/playwright/cinema-panel-mobile.png'});
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'output/playwright/cinema-panel-desktop.png'});
  await page.emulateMedia({media:'print'});
  ok(!await root.isVisible()&&!await page.locator('[data-cinema-open]').isVisible(),'Print layout excludes player and launcher');
  await page.emulateMedia({media:'screen'});
  await page.locator('[data-cinema-minimize]').click();
  await page.screenshot({path:'output/playwright/cinema-launcher-desktop.png'});
  const context=await page.context().browser().newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const fallback=await context.newPage();await fallback.goto(base+'/');
  ok(!await fallback.locator('[data-project-cinema]').isVisible()&&!await fallback.locator('[data-cinema-open]').isVisible(),'No-JS page hides unavailable floating controls');
  await fallback.locator('.film-disclosure summary').click();
  ok(await fallback.locator('#project-films').isVisible()&&await fallback.locator('#project-films').evaluate(e=>getComputedStyle(e).position!=='fixed'),'Original gallery is readable without JavaScript');
  await context.close();
  ok(errors.length===0,'No page script exceptions');
  return {passed:checks.length,checks,scans,errors,videoRequests:requests.length};
}
