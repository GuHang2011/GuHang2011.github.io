async page => {
  const base='http://127.0.0.1:8777', checks=[],errors=[],scans=[];
  const ok=(condition,label)=>{if(!condition)throw Error(label);checks.push(label)};
  page.on('pageerror',e=>errors.push(e.message));
  await page.unrouteAll({behavior:'ignoreErrors'});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'/?v=functional-test#work');
  await page.locator('[data-language="zh"]').click();
  await page.locator('#project-search').fill('KICP');
  ok(new URL(await page.evaluate(()=>location.href)).searchParams.get('project-q')==='KICP','Project query is shareable');
  await page.reload();
  ok(await page.locator('#project-search').inputValue()==='KICP'&&await page.locator('.project-item:visible').count()===1,'Query and results survive reload');
  ok(new URL(await page.evaluate(()=>location.href)).searchParams.get('v')==='functional-test','Unrelated URL parameters retained');
  await page.locator('[data-clear-search]').click();
  ok(!new URL(await page.evaluate(()=>location.href)).searchParams.has('project-q'),'Clear removes saved query');
  await page.locator('[data-filter-group="projects"] [data-filter="engineering"]').click();
  const filtered=await page.locator('.project-item:visible').count();
  await page.reload();
  ok(await page.locator('.project-item:visible').count()===filtered,'Category survives reload');
  await page.goBack();
  ok(await page.locator('.project-item:visible').count()===3,'Back restores curated projects');
  await page.goForward();
  ok(await page.locator('[data-filter-group="projects"] [data-filter="engineering"]').getAttribute('aria-pressed')==='true','Forward restores category');
  await page.goto(base+'/?project=invalid&project-q=missing-qz#work');
  ok(await page.locator('[data-project-empty]').isVisible(),'Unknown category falls back; empty query result is explained');
  await page.locator('[data-reset-projects]').click();
  ok(await page.locator('.project-item:visible').count()===13&&await page.locator('#project-search').inputValue()==='','Reset clears category and query');
  await page.locator('[data-project-expand]').click();await page.reload();
  ok(await page.locator('.project-item:visible').count()===3,'Collapsed view survives reload');
  await page.goto(base+'/?project=teaching&project-q=missing-qz#project-kapt');
  ok(await page.locator('#project-kapt').isVisible()&&!new URL(await page.evaluate(()=>location.href)).searchParams.has('project-q'),'Project deep link resolves conflicting filters');
  await page.goto(base+'/?v=functional-test#notebook');
  await page.locator('[data-desk-topic="engineering"]').click();
  await page.reload();
  ok(await page.locator('[data-desk-topic="engineering"]').getAttribute('aria-pressed')==='true','Note category survives reload');
  await page.goBack();
  ok(await page.locator('[data-desk-note]:visible').count()===3,'Back restores recent notes');
  await page.goto(base+'/#film-host');
  const video=page.locator('#film-host video');await video.evaluate(v=>{v.muted=true;return v.play()});
  await page.locator('[data-video-tab]').last().click();
  const selected=await page.locator('[data-video-tab][aria-selected="true"]').getAttribute('data-video-tab');
  ok(new URL(await page.evaluate(()=>location.href)).hash==='#'+selected,'Selected video and share link agree');
  ok(await video.evaluate(v=>v.paused),'Changing video pauses previous playback');
  await page.reload();
  ok(await page.locator('[data-video-tab][aria-selected="true"]').getAttribute('data-video-tab')===selected,'Selected video survives reload');
  await page.goBack();
  ok(await page.locator('[data-video-tab][aria-selected="true"]').getAttribute('data-video-tab')==='film-host','Back restores previous video');
  await page.locator('[data-video-tab][aria-selected="true"]').press('ArrowRight');
  ok(new URL(await page.evaluate(()=>location.href)).hash==='#'+await page.locator('[data-video-tab][aria-selected="true"]').getAttribute('data-video-tab'),'Keyboard video navigation updates link');
  await page.goto(base+'/');
  ok(await page.locator('img[data-en-alt][data-zh-alt]').evaluateAll(images=>images.every(image=>image.alt===image.dataset.zhAlt)),'All supplied homepage image translations match Chinese');
  const trigger=page.locator('#project-shuyang [data-preview]');
  const cover=trigger.locator('img');
  ok(await cover.getAttribute('alt')===await cover.getAttribute('data-zh-alt'),'Chinese image description is applied');
  let releaseImage;
  const gate=new Promise(resolve=>{releaseImage=resolve});
  await page.route('**/assets/shuyang-home/desktop-home.png',async route=>{await gate;await route.abort()});
  await trigger.click();
  ok((await page.locator('.preview-status').textContent()).includes('正在加载'),'Slow image has a loading message');
  releaseImage();await page.locator('[data-preview-retry]').waitFor({state:'visible'});
  ok((await page.locator('.preview-status').textContent()).includes('未能加载'),'Failed image has a recovery message');
  ok(await page.locator('.preview-actions a').getAttribute('href')==='assets/shuyang-home/desktop-home.png','Original image remains accessible');
  await page.screenshot({path:'output/playwright/functional-preview-error.png'});
  await page.addScriptTag({path:'output/frontend-audit/node_modules/axe-core/axe.min.js'});
  const modalViolations=await page.evaluate(async()=>(await axe.run(document.querySelector('.lightbox'),{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}})).violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)})));
  scans.push({scope:'failed screenshot',violations:modalViolations});ok(!modalViolations.length,'Error dialog accessibility');
  await page.unroute('**/assets/shuyang-home/desktop-home.png');
  await page.locator('[data-preview-retry]').click();
  await page.waitForFunction(()=>{const image=document.querySelector('.lightbox-image');return !image.hidden&&image.complete&&image.naturalWidth>0});
  ok(await page.locator('.preview-status').isHidden()&&await page.locator('[data-preview-retry]').isHidden(),'Retry restores image and removes error');
  await page.keyboard.press('Escape');
  ok(await trigger.evaluate(el=>el===document.activeElement),'Closing preview restores trigger focus');
  // A late result from a closed preview must not alter the newly opened one.
  let releaseOld,finishOld;
  const oldGate=new Promise(resolve=>{releaseOld=resolve});
  const oldDone=new Promise(resolve=>{finishOld=resolve});
  await page.route('**/assets/shuyang-home/desktop-home.png',async route=>{await oldGate;await route.abort();finishOld()});
  await trigger.click();await page.keyboard.press('Escape');
  await page.locator('#project-counselor [data-preview]').click();
  await page.waitForFunction(()=>document.querySelector('.lightbox-image').naturalWidth>0);
  releaseOld();await oldDone;await page.unroute('**/assets/shuyang-home/desktop-home.png');
  ok((await page.locator('.lightbox-image').getAttribute('src')).includes('counselor')&&await page.locator('.preview-status').isHidden(),'Late failure cannot replace a different screenshot');
  await page.keyboard.press('Escape');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.locator('[data-reader-toggle]').click();
  await page.locator('[data-reduce-motion]').focus();await page.keyboard.press('Tab');
  ok(await page.locator('[data-reader-toggle]').getAttribute('aria-expanded')==='false','Tab out closes reader preferences');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.evaluate(()=>window.scrollTo(0,document.documentElement.scrollHeight));
  await page.locator('.back-top').click();
  ok(await page.evaluate(()=>scrollY===0&&document.activeElement.id==='main'),'Back to top returns keyboard focus to content');
  for(const path of ['/','/research/statement.html']){
    await page.goto(base+path);
    await page.locator('details').first().evaluate(el=>el.open=true);
    const state=()=>page.evaluate(()=>({details:[...document.querySelectorAll('details')].map(e=>e.open),hidden:[...document.querySelectorAll('[data-collection] [data-category], [data-desk-note]')].map(e=>e.hidden)}));
    const before=await state();
    await page.evaluate(()=>{dispatchEvent(new Event('beforeprint'));dispatchEvent(new Event('beforeprint'))});
    ok(await page.locator('details:not([open])').count()===0,'Print expands evidence '+path);
    await page.evaluate(()=>{dispatchEvent(new Event('afterprint'));dispatchEvent(new Event('afterprint'))});
    ok(JSON.stringify(before)===JSON.stringify(await state()),'Repeated print events restore original view '+path);
  }
  await page.goto(base+'/#notebook');
  for(const lang of ['zh','en']){
    await page.locator('[data-language="'+lang+'"]').click();
    for(const width of [320,390,768,1440]){
      await page.setViewportSize({width,height:900});
      ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Homepage fits '+lang+'/'+width);
    }
  }
  for(const theme of ['light','dark']){
    await page.locator('[data-reader-toggle]').click();await page.locator('button[data-reader-theme="'+theme+'"]').click();await page.keyboard.press('Escape');
    await page.addScriptTag({path:'output/frontend-audit/node_modules/axe-core/axe.min.js'});
    const violations=await page.evaluate(async()=>(await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}})).violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>({target:n.target,reason:n.failureSummary}))})));
    scans.push({scope:'homepage '+theme,violations});ok(!violations.length,'Homepage accessibility '+theme+JSON.stringify(violations));
  }
  await page.locator('[data-reader-toggle]').click();await page.locator('button[data-reader-theme="light"]').click();await page.keyboard.press('Escape');
  await page.setViewportSize({width:390,height:844});
  await page.locator('.menu-toggle').click();await page.locator('#navigation a[href="#work"]').click();
  ok(await page.locator('.menu-toggle').getAttribute('aria-expanded')==='false','Mobile navigation closes');
  await page.waitForFunction(()=>document.activeElement.id==='work');
  ok(await page.locator('#work').evaluate(el=>el.getBoundingClientRect().top>=60),'Mobile anchor focus clears header');
  await page.locator('#project-shuyang [data-preview]').click();
  await page.waitForFunction(()=>document.querySelector('.lightbox-image').naturalWidth>0);
  ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Image viewer fits mobile');
  await page.keyboard.press('Escape');
  const context=await page.context().browser().newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const fallback=await context.newPage();await fallback.goto(base+'/');
  ok(await fallback.locator('.project-item:visible').count()===13,'All projects remain readable without JavaScript');
  ok(await fallback.locator('#project-filter-help').isHidden(),'No-JS page does not promise interactive filtering');
  await context.close();
  ok(errors.length===0,'No JavaScript exceptions');
  return {passed:checks.length,checks,scans,errors};
}
